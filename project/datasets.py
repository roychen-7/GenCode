import os
import numpy as np
import pandas as pd
import torch

from torch.utils.data import TensorDataset, DataLoader


# ----------------------------------------------------
# FULL Alpha158 loader (using Qlib offline cn_data)
# ----------------------------------------------------
def load_full_dataset(
    root="project/data/cn_data",
    instruments="all",
    start_date="2010-01-01",
    end_date="2020-12-31",
    batch_size=1024,
    shuffle=True
):
    """
    Loads Alpha158 features from qlib's cn_data offline dataset.

    It expects that:
      project/data/cn_data/ exists and was generated by:
          qlib_data --source cn_data --target_dir project/data/cn_data

    Returns:
       PyTorch DataLoader (features, labels)
    """

    try:
        import qlib
        from qlib.data import D
        from qlib.contrib.data.dataset import DatasetH
        from qlib.contrib.data.handler import Alpha158
    except Exception:
        raise ImportError("Qlib is required: pip install pyqlib")

    # initialize qlib once
    qlib.init(
        provider_uri=root,
        region="cn"
    )

    handler = Alpha158(
        instruments=instruments,
        start_time=start_date,
        end_time=end_date,
        infer_processors=[],
        learn_processors=[],
        label=["Ref($close, -1)/$close-1"]
    )

    dataset = DatasetH(handler, segments={
        "train": (start_date, end_date)
    })

    df = dataset.prepare("train", col_set="feature,label", data_key=DataHandlerLP.DK_L)

    # Drop NA
    df = df.dropna()

    X = df["feature"].values.astype(np.float32)
    y = df["label"].values.astype(np.float32).reshape(-1, 1)

    ds = TensorDataset(torch.from_numpy(X), torch.from_numpy(y))

    return DataLoader(ds, batch_size=batch_size, shuffle=shuffle)
